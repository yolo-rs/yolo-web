/**
 * Writes the resolved design tokens in the replica-design `tokens.json`
 * format: the color roles of every theme in every scheme it renders in (the
 * seed themes with the default seed), the text and boundary pairs the page
 * draws, and the type, space, radius and motion scales. The replica-design
 * `contrast.py` checks the file:
 *
 *   bun run scripts/tokens-json.ts <out.json>
 *   python contrast.py <out.json>
 */
import {
  type ColorRoles,
  rolesFor,
  SURFACE_ROLES,
} from "../src/newtab/scheme.ts";
import {
  DEFAULT_SEED,
  FONT_STACK,
  MOTION,
  SPACE,
  THEMES,
  TYPE,
} from "../src/tokens.ts";

const kebab = (name: string): string =>
  name.replace(/[A-Z]/g, (char) => `-${char.toLowerCase()}`);

const TEXT_ON: ReadonlyArray<readonly [keyof ColorRoles, keyof ColorRoles]> = [
  ...SURFACE_ROLES.flatMap((bg) =>
    (["onSurface", "onSurfaceVariant", "primary", "error"] as const).map(
      (fg) => [fg, bg] as const,
    ),
  ),
  ["onPrimary", "primary"],
  ["onSecondaryContainer", "secondaryContainer"],
  ["inverseOnSurface", "inverseSurface"],
  ["inversePrimary", "inverseSurface"],
];

export function tokensJson(): Record<string, unknown> {
  const color: Record<string, Record<string, string>> = {};
  const pairs: string[][] = [];
  for (const theme of THEMES) {
    const schemes = theme.scheme
      ? [theme.scheme]
      : (["light", "dark"] as const);
    for (const scheme of schemes) {
      const key = `${theme.id}-${scheme}`;
      const roles = rolesFor(theme, DEFAULT_SEED, scheme);
      color[key] = Object.fromEntries(
        Object.entries(roles).map(([role, hex]) => [kebab(role), hex]),
      );
      for (const [fg, bg] of TEXT_ON) {
        pairs.push([`${key}-${kebab(fg)}`, `${key}-${kebab(bg)}`]);
      }
      for (const bg of SURFACE_ROLES) {
        pairs.push([`${key}-outline`, `${key}-${kebab(bg)}`, "ui"]);
      }
    }
  }
  return {
    _about:
      "Generated by packages/chrome-extension-yolo/scripts/tokens-json.ts from src/tokens.ts and src/scheme.ts. Seed themes use the default seed " +
      DEFAULT_SEED,
    color,
    pairs,
    font: { sans: FONT_STACK },
    type: TYPE,
    space: SPACE,
    radius: Object.fromEntries(THEMES.map((theme) => [theme.id, theme.shape])),
    motion: MOTION,
  };
}

if (import.meta.main) {
  const out = Bun.argv[2];
  if (!out) {
    throw new Error("usage: bun run scripts/tokens-json.ts <out.json>");
  }
  await Bun.write(out, `${JSON.stringify(tokensJson(), null, 2)}\n`);
  console.log(out);
}
