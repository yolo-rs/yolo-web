/**
 * Compiles the yolo-agent CLI into single executables with the extension
 * embedded:  bun run scripts/compile.ts [targets]
 *
 * targets: comma list of windows-x64, linux-x64, darwin-arm64 (default: host).
 * Flags: `bun build --compile --bytecode --minify`. Output: dist/bin/.
 * The embedded extension is generated into src/embedded-extension.ts for the
 * build and the committed stub is restored afterwards.
 */
import { mkdir, readdir } from "node:fs/promises";
import { join, relative, resolve } from "node:path";
import { DIST, buildExtension } from "./build-extension.ts";

const ROOT = resolve(import.meta.dir, "..");
const STUB_PATH = join(ROOT, "src", "embedded-extension.ts");
const ALL_TARGETS = ["windows-x64", "linux-x64", "darwin-arm64"] as const;

async function walk(dir: string): Promise<string[]> {
  const out: string[] = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...(await walk(path)));
    else out.push(path);
  }
  return out;
}

const hostTarget = `${process.platform === "win32" ? "windows" : process.platform}-${process.arch === "arm64" ? "arm64" : "x64"}`;
const requested = (Bun.argv[2] ?? hostTarget).split(",");
for (const t of requested) {
  if (!(ALL_TARGETS as readonly string[]).includes(t))
    throw new Error(`unsupported target ${t}; use ${ALL_TARGETS.join(", ")}`);
}

await buildExtension();
const embedded: Record<string, string> = {};
for (const file of await walk(DIST)) {
  embedded[relative(DIST, file).replaceAll("\\", "/")] = Buffer.from(
    await Bun.file(file).arrayBuffer(),
  ).toString("base64");
}
const stub = await Bun.file(STUB_PATH).text();
await Bun.write(
  STUB_PATH,
  `// SPDX-License-Identifier: Apache-2.0\n// GENERATED by scripts/compile.ts; the committed stub exports null.\nexport const EMBEDDED_EXTENSION: Record<string, string> | null = ${JSON.stringify(embedded)};\n`,
);

const outDir = join(ROOT, "dist", "bin");
await mkdir(outDir, { recursive: true });
const sizes: Record<string, string> = {};
try {
  for (const target of requested) {
    const outfile = join(
      outDir,
      `yolo-agent-${target}${target.startsWith("windows") ? ".exe" : ""}`,
    );
    const t0 = performance.now();
    const result = await Bun.build({
      entrypoints: [join(ROOT, "src", "cli.ts")],
      compile: { target: `bun-${target}` as never, outfile },
      bytecode: true,
      minify: true,
    });
    if (!result.success) {
      console.error(
        `${target}: build failed\n${result.logs.map(String).join("\n")}`,
      );
      process.exitCode = 1;
      continue;
    }
    const size = Bun.file(outfile).size;
    sizes[target] =
      `${(size / 1024 / 1024).toFixed(1)} MiB in ${Math.round(performance.now() - t0)} ms`;
    console.log(`${target}: ${outfile} ${sizes[target]}`);
  }
} finally {
  await Bun.write(STUB_PATH, stub);
}
